def parse_numbers(text):
    """
    Преобразует введенный текст в массив чисел.
    Поддерживает запятые и точки в качестве десятичного разделителя.
    Разделители: пробел, перенос строки, точка с запятой.
    """
    if not text.strip():
        return np.array([])

    cleaned = (
        text.replace(",", ".")
            .replace(";", " ")
            .replace("\n", " ")
            .replace("\t", " ")
    )

    values = []
    for item in cleaned.split():
        try:
            values.append(float(item))
        except ValueError:
            pass

    return np.array(values, dtype=float)


def type_a_uncertainty(values):
    """
    Расчет среднего значения, СКО и стандартной неопределенности типа A.
    """
    n = len(values)

    if n == 0:
        return np.nan, np.nan, np.nan, 0

    mean = np.mean(values)

    if n == 1:
        std = 0.0
        u_a = 0.0
    else:
        std = np.std(values, ddof=1)
        u_a = std / np.sqrt(n)

    return mean, std, u_a, n


def limit_error_from_class(range_value, accuracy_class_percent, resolution):
    """
    Предельная абсолютная погрешность цифрового прибора.

    Упрощенная модель:
    Δ = γ * Xmax / 100 + q / 2

    где:
    γ — класс точности прибора, %
    Xmax — выбранный предел измерения
    q — цена младшего разряда / разрешение прибора
    """
    return abs(range_value) * accuracy_class_percent / 100 + resolution / 2


def safe_relative(delta, value):
    """
    Относительная погрешность в процентах.
    """
    if value == 0 or np.isnan(value):
        return np.nan
    return abs(delta / value) * 100


