def generate_initial_data(variant: int):
    """
    Генерирует исходные данные для практической работы по номеру варианта.
    Автоматические расчеты результатов измерения не выполняются.
    Генерируются только экспериментальные данные и параметры приборов.
    """

    rng = np.random.default_rng(1000 + variant)

    # Количество измерений
    n = int(rng.integers(7, 11))

    # Номинальные значения для генерации экспериментальных данных
    R_nominal = rng.choice([22, 33, 47, 68, 82, 100, 120, 150, 180, 220])
    I_nominal = rng.uniform(0.035, 0.095)
    U_nominal = R_nominal * I_nominal

    # Случайный разброс измерений
    U_noise = rng.normal(0, 0.015, n)
    I_noise = rng.normal(0, 0.0006, n)

    U_values = U_nominal + U_noise
    I_values = I_nominal + I_noise

    # Округление, как у цифровых приборов
    U_values = np.round(U_values, 3)
    I_values = np.round(I_values, 5)

    # Параметры вольтметра
    if U_nominal <= 5:
        U_range = 10.0
    elif U_nominal <= 15:
        U_range = 20.0
    else:
        U_range = 50.0

    U_accuracy_class = rng.choice([0.2, 0.5, 1.0])
    U_resolution = rng.choice([0.001, 0.01])

    # Параметры амперметра
    I_range = rng.choice([0.1, 0.2, 0.5])
    if I_nominal > I_range:
        I_range = 0.5

    I_accuracy_class = rng.choice([0.2, 0.5, 1.0])
    I_resolution = rng.choice([0.0001, 0.001])

    # Коэффициент охвата
    k = 2.0

    # Закон распределения для типа B
    distribution = "Равномерное распределение"

    measurement_df = pd.DataFrame(
        {
            "№ измерения": np.arange(1, n + 1),
            "Напряжение U, В": U_values,
            "Ток I, А": I_values
        }
    )

    instruments_df = pd.DataFrame(
        {
            "Средство измерения": [
                "Вольтметр",
                "Амперметр"
            ],
            "Предел измерения": [
                U_range,
                I_range
            ],
            "Класс точности, %": [
                U_accuracy_class,
                I_accuracy_class
            ],
            "Разрешение": [
                U_resolution,
                I_resolution
            ],
            "Единица": [
                "В",
                "А"
            ]
        }
    )

    uncertainty_params_df = pd.DataFrame(
        {
            "Параметр": [
                "Коэффициент охвата k",
                "Закон распределения для неопределенности типа B"
            ],
            "Значение": [
                k,
                distribution
            ]
        }
    )

    return measurement_df, instruments_df, uncertainty_params_df


